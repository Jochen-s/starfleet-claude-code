/**
 * Format a task status into a bracketed text marker.
 *
 * @param {string} status
 * @returns {string}
 */
function statusMarker(status) {
  switch ((status || '').toLowerCase()) {
    case 'completed': return '[completed]';
    case 'in_progress': return '[in_progress]';
    case 'pending': return '[pending]';
    case 'cancelled': return '[cancelled]';
    default: return `[${(status || 'unknown').replace(/[\r\n\[\]()]/g, '')}]`;
  }
}

/**
 * Build the full HANDOFF.md content string.
 *
 * @param {{ currentTask: string|null, hullIntegrity: string }} checkpoint
 * @param {object[]} actions
 * @param {object[]} tasks
 * @param {string[]} promises  Pre-extracted promise phrases
 * @param {{ completed: object[], newTasks: object[], stalled: object[], abandoned: object[], removed: object[] }} [delta]
 * @param {string} [lastMessage]  Last assistant message from hook input
 * @param {string[]} [decisions]  Decision texts extracted by pre-compact-retention
 * @param {string} [projectRoot]  Project root path, used for scope tagging
 * @returns {string}
 */
function renderHandoff(checkpoint, actions, tasks, promises, delta, lastMessage, decisions, projectRoot) {
  const now      = new Date().toISOString();
  const hull     = checkpoint.hullIntegrity;
  const task     = checkpoint.currentTask || 'No active task';

  const completedActions = extractCompletedActions(actions);
  const modifiedFiles    = extractModifiedFiles(actions);

  // Sort tasks: in_progress first, then pending, then others
  const statusOrder = { in_progress: 0, pending: 1 };
  const sortedTasks = [...tasks].sort((a, b) => {
    const aOrd = statusOrder[(a.status || '').toLowerCase()] ?? 9;
    const bOrd = statusOrder[(b.status || '').toLowerCase()] ?? 9;
    return aOrd - bOrd;
  });

  let md = '';

  // Header
  md += `# Captain's Log, Supplemental\n\n`;
  md += `*Auto-generated: ${now}*\n`;
  md += `*Hull integrity: ${hull}*\n\n`;

  // Mission Status
  md += `## Mission Status\n\n`;
  md += `**Current task**: ${task}\n\n`;

  // Last Words (final assistant message before session ended)
  if (lastMessage) {
    md += `## Last Words\n\n`;
    md += `> ${lastMessage.slice(0, 500).replace(/\n/g, '\n> ')}\n\n`;
  }

  // Completed Actions
  md += `## Completed Actions\n\n`;
  if (completedActions.length > 0) {
    for (const action of completedActions) {
      md += `- ${action}\n`;
    }
  } else {
    md += `- No Edit/Write/Bash actions recorded this session\n`;
  }
  md += '\n';

  // Active Tasks
  md += `## Active Tasks\n\n`;
  if (sortedTasks.length > 0) {
    for (const t of sortedTasks) {
      const marker  = statusMarker(t.status);
      const id      = t.id      ? `#${t.id}`    : '';
      const subject = sanitizeForMd(t.subject || t.description || 'Unnamed task');
      const idPart  = id ? `${id}: ` : '';
      md += `- ${marker} ${idPart}${subject}\n`;
    }
  } else {
    md += `- No tasks recorded (task-snapshot.json absent or empty)\n`;
  }
  md += '\n';

  // Mission Delta (planned-vs-achieved)
  if (delta) {
    const hasContent = delta.completed.length || delta.newTasks.length ||
                       delta.stalled.length || delta.abandoned.length ||
                       delta.removed.length;
    md += `## Mission Delta\n\n`;
    if (hasContent) {
      if (delta.completed.length > 0) {
        md += `**Completed this session** (${delta.completed.length}):\n`;
        for (const t of delta.completed) {
          md += `- ${sanitizeForMd(t.subject)}\n`;
        }
        md += '\n';
      }
      if (delta.newTasks.length > 0) {
        md += `**Created this session** (${delta.newTasks.length}):\n`;
        for (const t of delta.newTasks) {
          md += `- [${t.delta}] ${sanitizeForMd(t.subject)}\n`;
        }
        md += '\n';
      }
      if (delta.stalled.length > 0) {
        md += `**Still in progress** (${delta.stalled.length}):\n`;
        for (const t of delta.stalled) {
          md += `- ${sanitizeForMd(t.subject)}\n`;
        }
        md += '\n';
      }
      if (delta.abandoned.length > 0) {
        md += `**Abandoned** (${delta.abandoned.length}):\n`;
        for (const t of delta.abandoned) {
          md += `- ${sanitizeForMd(t.subject)}\n`;
        }
        md += '\n';
      }
      if (delta.removed.length > 0) {
        md += `**Removed** (${delta.removed.length}):\n`;
        for (const t of delta.removed) {
          md += `- ${sanitizeForMd(t.subject)}\n`;
        }
        md += '\n';
      }
    } else {
      md += `*No task status changes recorded this session.*\n\n`;
    }
  }

  // Files Modified
  md += `## Files Modified\n\n`;
  if (modifiedFiles.length > 0) {
    for (const f of modifiedFiles) {
      md += `- \`${sanitizeForMd(f)}\`\n`;
    }
  } else {
    md += `- No files modified via Edit or Write this session\n`;
  }
  md += '\n';

  // Recent Decisions (with scope tagging)
  if (Array.isArray(decisions) && decisions.length > 0) {
    md += `## Recent Decisions\n\n`;
    for (const d of decisions) {
      const text  = sanitizeForMd(d);
      const scope = decisionScope(d, projectRoot);
      md += `- [${scope}] ${text}\n`;
    }
    md += '\n';
  }

  // Promises Made
  if (promises.length > 0) {
    md += `## Promises Made This Session\n\n`;
    for (const p of promises) {
      md += `- ${sanitizeForMd(p)}\n`;
    }
    md += '\n';
  }

  // Recommended Next Steps
  md += `## Recommended Next Steps\n\n`;
  md += `1. Run \`/resume\` to restore session context\n`;
  md += `2. Check task list with \`TaskList\` for pending work\n`;
  md += `3. Review files modified above for completeness\n\n`;

  // Footer: must contain AUTO_GENERATED_MARKER (used by external tooling,
  // e.g. the W0-4 rename-manifest classifier, to identify auto-dumps)
  md += `---\n`;
  md += `*${AUTO_GENERATED_MARKER} (Stop event)*\n`;

  return md;
}

// ---------------------------------------------------------------------------
// Atomic write
// ---------------------------------------------------------------------------

/**
 * Write content to dest atomically: write to a .tmp file, then rename.
 * Ensures no partial reads if the process is interrupted mid-write.
 *
 * @param {string} dest      Absolute path to target file
 * @param {string} content   File content string
 */
function atomicWrite(dest, content) {
  const tmp = dest + '.tmp';
  fs.writeFileSync(tmp, content, 'utf8');
  fs.renameSync(tmp, dest);
}

