#!/usr/bin/env node
/**
 * Captain's Log: Stop event hook for Claude Code.
 *
 * Fires on the Stop event (session ending). Reads from lightweight cache
 * files to generate a HANDOFF-auto.md in the project root, giving the next
 * session a clear picture of what was accomplished and what remains.
 *
 * Event:  Stop
 * Budget: <50ms (pure filesystem, no network, no LLM)
 * Output: {projectRoot}/HANDOFF-auto.md (always; this hook never creates or
 *         touches HANDOFF.md, which is reserved for curated manual handoffs)
 *
 * Data sources (all in ~/.claude/cache/):
 *   recent-actions.jsonl    : last 50 tool actions (circular buffer)
 *   session-checkpoint.json : hull integrity, currentTask, projectPath
 *   task-snapshot.json      : task list with status (may not exist)
 *
 * Failure policy: every error path exits 0. Never block the session.
 */

'use strict';

const { shouldFire } = require('./lib/hook-gate');
if (!shouldFire('captain-log')) process.exit(0);

const fs   = require('fs');
const path = require('path');
const os   = require('os');

// ---------------------------------------------------------------------------
// Constants
// ---------------------------------------------------------------------------

const CACHE_DIR          = path.join(os.homedir(), '.claude', 'cache');
const RECENT_ACTIONS     = path.join(CACHE_DIR, 'recent-actions.jsonl');
const SESSION_CHECKPOINT = path.join(CACHE_DIR, 'session-checkpoint.json');
const TASK_SNAPSHOT      = path.join(CACHE_DIR, 'task-snapshot.json');

/** Resolve the session-start snapshot path, scoped by task list ID to prevent cross-session corruption */
function getStartTasksPath() {
  const listId = process.env.CLAUDE_CODE_TASK_LIST_ID || 'default';
  return path.join(CACHE_DIR, `session-start-tasks-${listId}.json`);
}

/** Tool names that represent meaningful file work */
const FILE_TOOLS = new Set(['Edit', 'Write']);

/** Tool names to include in the Completed Actions list */
const ACTION_TOOLS = new Set(['Edit', 'Write', 'Bash']);

/** Max recent actions to surface in the report */
const MAX_ACTIONS = 10;

/** Max file size guard for cache reads (32KB) */
const MAX_CACHE_BYTES = 32 * 1024;

/** Marker present in all auto-generated handoff footers */
const AUTO_GENERATED_MARKER = 'Generated by Captain\'s Log hook';

/** Patterns that indicate promises/commitments in assistant responses */
const PROMISE_PATTERNS = [
  /\bI will\b/i,
  /\bI'll\b/i,
  /\bI'm going to\b/i,
  /\bnext I'll\b/i,
  /\blet me (?:now |then )?(?:go ahead and |proceed to )?(?:implement|create|add|fix|update|write|build|set up|configure|deploy)/i,
];

const PROMISES_FILE    = path.join(CACHE_DIR, 'promises.json');
const STALE_PROMISE_DAYS = 7;

/** Vault path for session digests (opt-in via env var) */
const VAULT_SESSIONS_DIR = process.env.CLAUDE_VAULT_SESSIONS_DIR || null;

/** Max vault digest age before pruning (days) */
const VAULT_RETENTION_DAYS = 30;

// ---------------------------------------------------------------------------
// Decision scope tagging
// ---------------------------------------------------------------------------

/**
 * Classify a decision's scope based on whether it references the current project.
 * Returns 'project' if the text references the project name or project-specific
 * language; returns 'global' for general patterns applicable across projects.
 *
 * @param {string} text         The decision text to classify
 * @param {string} [projectDir] The project root directory path
 * @returns {'project'|'global'}
 */
function decisionScope(text, projectDir) {
  const projectName = path.basename(projectDir || '').toLowerCase();
  const textLower = text.toLowerCase();
  if (projectName && projectName.length > 2 && textLower.includes(projectName)) return 'project';
  if (/\b(this project|this repo|this codebase|here we)\b/i.test(text)) return 'project';
  return 'global';
}

// ---------------------------------------------------------------------------
// Path safety
// ---------------------------------------------------------------------------

/**
 * Validate that a project root path is safe to write into.
 * Rejects paths inside ~/.claude/ (config dir) and non-existent dirs.
 *
 * @param {string} p
 * @returns {boolean}
 */
function isSafeProjectRoot(p) {
  if (!p || typeof p !== 'string') return false;
  try {
    const resolved = path.resolve(p);
    const claudeDir = path.join(os.homedir(), '.claude');
    if (resolved.startsWith(claudeDir + path.sep) || resolved === claudeDir) return false;
    return fs.existsSync(resolved) && fs.statSync(resolved).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Resolve the target path for the handoff file.
 *
 * Always HANDOFF-auto.md. This hook never creates or overwrites HANDOFF.md:
 * that name is reserved for curated manual handoffs (/handoff or hand-written).
 * Inverted 2026-07-15 (portfolio plan W0-4): the old default of writing
 * HANDOFF.md when none existed seeded auto-dumps as the de-facto handoff in
 * at least 14 project roots, sometimes describing a different project
 * (global cache files are shared across concurrent sessions).
 *
 * @param {string} projectRoot
 * @returns {string}  Absolute path to write the handoff
 */
function resolveHandoffTarget(projectRoot) {
  return path.join(path.resolve(projectRoot), 'HANDOFF-auto.md');
}

/**
 * Sanitize a string for safe Markdown interpolation.
 * Strips newlines and leading Markdown-structural characters.
 *
 * @param {string} s
 * @returns {string}
 */
function sanitizeForMd(s) {
  if (typeof s !== 'string') return '';
  return s.replace(/[\r\n]+/g, ' ').replace(/^[#>\[]+\s*/, '').replace(/[*_`]/g, '').slice(0, 200);
}

// ---------------------------------------------------------------------------
// Safe readers
// ---------------------------------------------------------------------------

/**
 * Read a JSON file, returning `fallback` on any error or if file exceeds
 * the size cap. Never throws.
 *
 * @param {string} filePath
 * @param {*} fallback
 * @returns {*}
 */
function safeReadJson(filePath, fallback) {
  try {
    const raw = fs.readFileSync(filePath, 'utf8');
    if (raw.length > MAX_CACHE_BYTES) return fallback;
    return JSON.parse(raw);
  } catch {
    return fallback;
  }
}

/**
 * Read a JSONL file into an array of parsed objects.
 * Skips unparseable lines. Returns [] on any error.
 *
 * @param {string} filePath
 * @returns {object[]}
 */
function safeReadJsonl(filePath) {
  try {
    const raw = fs.readFileSync(filePath, 'utf8');
    if (raw.length > MAX_CACHE_BYTES) return [];
    return raw
      .trim()
      .split('\n')
      .filter(Boolean)
      .map(line => {
        try { return JSON.parse(line); } catch { return null; }
      })
      .filter(Boolean);
  } catch {
    return [];
  }
}

// ---------------------------------------------------------------------------
// Data extraction helpers
// ---------------------------------------------------------------------------

/**
 * Load and return the session checkpoint data.
 * Returns a safe defaults object if the file is missing or malformed.
 *
 * @returns {{ currentTask: string|null, hullIntegrity: string, projectPath: string|null }}
 */
function loadCheckpoint() {
  const data = safeReadJson(SESSION_CHECKPOINT, {});
  return {
    currentTask:   data.currentTask   || null,
    hullIntegrity: data.hullIntegrity || 'Unknown',
    projectPath:   data.projectPath   || null,
  };
}

/**
 * Load task list by scanning the task directory directly.
 * Falls back to task-snapshot.json if directory scan yields nothing.
 *
 * @param {string} [sessionId]  Optional session ID for session-based task dirs
 * @returns {Array<{ id: string, subject: string, status: string }>}
 */
function loadTasks(sessionId) {
  const tasks = scanTaskDirectory(sessionId);
  if (tasks.length > 0) return tasks;

  // Fallback: try task-snapshot.json (legacy)
  const data = safeReadJson(TASK_SNAPSHOT, null);
  if (!data) return [];
  if (Array.isArray(data.tasks)) return data.tasks;
  if (Array.isArray(data)) return data;
  return [];
}

/**
 * Scan ~/.claude/tasks/<list-id>/ for task JSON files.
 * Uses CLAUDE_CODE_TASK_LIST_ID and optionally hookData session_id.
 *
 * @param {string} [sessionId]  Optional session ID to also scan session-based task dir
 * @returns {Array<{ id: string, subject: string, status: string }>}
 */
function scanTaskDirectory(sessionId) {
  const tasks = [];
  const seen = new Set();
  try {
    const tasksBase = path.join(os.homedir(), '.claude', 'tasks');
    if (!fs.existsSync(tasksBase)) return tasks;

    const taskListId = process.env.CLAUDE_CODE_TASK_LIST_ID || '';
    const dirsToScan = [];
    if (taskListId) dirsToScan.push(path.join(tasksBase, taskListId));
    if (sessionId) dirsToScan.push(path.join(tasksBase, sessionId));

    for (const dir of dirsToScan) {
      if (!fs.existsSync(dir)) continue;
      try {
        const stat = fs.statSync(dir);
        if (!stat.isDirectory()) continue;
      } catch { continue; }
      const files = fs.readdirSync(dir).filter(f => f.endsWith('.json'));
      for (const file of files) {
        try {
          const raw = fs.readFileSync(path.join(dir, file), 'utf8');
          if (raw.length > MAX_CACHE_BYTES) continue;
          const task = JSON.parse(raw);
          const id = task.id || file.replace('.json', '');
          if (seen.has(id)) continue;
          seen.add(id);
          tasks.push({
            id,
            subject: (task.subject || task.description || 'Unnamed').slice(0, 200),
            status: task.status || 'unknown',
          });
        } catch { /* skip malformed */ }
      }
    }
  } catch { /* non-critical */ }
  return tasks;
}

/**
 * Load the session-start task snapshot written by project-state-loader.
 *
 * @returns {Array<{ id: string, subject: string, status: string }>}
 */
function loadStartTasks() {
  const snapshotPath = getStartTasksPath();
  const data = safeReadJson(snapshotPath, null);
  if (!data || !Array.isArray(data.tasks)) return [];
  // Verify snapshot belongs to this project's task list
  const currentListId = process.env.CLAUDE_CODE_TASK_LIST_ID || 'default';
  if (data.taskListId && data.taskListId !== currentListId) return [];
  return data.tasks;
}

/**
 * Compute the delta between session-start tasks and current tasks.
 *
 * @param {Array<{ id: string, subject: string, status: string }>} startTasks
 * @param {Array<{ id: string, subject: string, status: string }>} endTasks
 * @returns {{ completed: object[], newTasks: object[], stalled: object[], abandoned: object[] }}
 */
function computeDelta(startTasks, endTasks) {
  const startMap = new Map(startTasks.map(t => [t.id, t]));
  const endMap = new Map(endTasks.map(t => [t.id, t]));

  const completed = [];   // Was not completed at start, now completed
  const newTasks = [];     // Didn't exist at start, exists now
  const stalled = [];      // Was in_progress at start, still in_progress at end
  const abandoned = [];    // Was active at start, now cancelled
  const removed = [];      // Existed at start, gone at end (deleted tasks)

  for (const [id, end] of endMap) {
    const start = startMap.get(id);
    const endStatus = (end.status || '').toLowerCase();

    if (!start) {
      // New task created this session
      newTasks.push({ ...end, delta: endStatus });
    } else {
      const startStatus = (start.status || '').toLowerCase();
      if (endStatus === 'completed' && startStatus !== 'completed') {
        completed.push(end);
      } else if (endStatus === 'in_progress' && startStatus === 'in_progress') {
        stalled.push(end);
      } else if (endStatus === 'cancelled' && startStatus !== 'cancelled') {
        abandoned.push(end);
      }
    }
  }

  // Tasks that existed at start but are gone now
  for (const [id, start] of startMap) {
    if (!endMap.has(id)) {
      removed.push(start);
    }
  }

  return { completed, newTasks, stalled, abandoned, removed };
}

/**
 * Load the recent-actions buffer and return only successful entries.
 *
 * @returns {object[]}
 */
function loadRecentActions() {
  return safeReadJsonl(RECENT_ACTIONS).filter(e => e.success !== false);
}

/**
 * Extract the last N successful Edit/Write/Bash actions for display.
 *
 * @param {object[]} actions
 * @returns {string[]}  Human-readable bullet strings
 */
function extractCompletedActions(actions) {
  const relevant = actions
    .filter(e => ACTION_TOOLS.has(e.tool))
    .slice(-MAX_ACTIONS);

  return relevant.map(e => {
    const toolName = String(e.tool || '').replace(/[^A-Za-z]/g, '');
    const label = e.file ? `${toolName}: \`${sanitizeForMd(e.file)}\`` : toolName;
    return label;
  });
}

/**
 * Collect unique file paths from Edit/Write actions.
 *
 * @param {object[]} actions
 * @returns {string[]}
 */
function extractModifiedFiles(actions) {
  const seen = new Set();
  for (const e of actions) {
    if (FILE_TOOLS.has(e.tool) && e.file) {
      seen.add(e.file);
    }
  }
  return [...seen];
}

/**
 * Extract promises from recent actions that contain assistant text.
 * Scans action descriptions for commitment patterns.
 *
 * @param {object[]} actions
 * @returns {string[]} Extracted promise phrases
 */
function extractPromises(actions) {
  const promises = [];
  for (const action of actions) {
    const text = (action.description || '').slice(0, 500);
    if (text.length < 10) continue;
    for (const pattern of PROMISE_PATTERNS) {
      const match = text.match(pattern);
      if (match) {
        const idx = text.indexOf(match[0]);
        const start = Math.max(0, idx - 20);
        const end = Math.min(text.length, idx + match[0].length + 80);
        const context = text.slice(start, end)
          .replace(/[\r\n\u0085\u2028\u2029]+/g, ' ')
          .trim()
          .slice(0, 200);
        if (context.length > 10) {
          promises.push(context);
        }
        break;
      }
    }
  }
  return promises;
}

/**
 * Save new promises and return stale ones (>7 days old).
 *
 * @param {string[]} newPromises
 * @returns {object[]} Stale promises with timestamp
 */
function updatePromises(newPromises) {
  if (newPromises.length === 0) return;

  const now = Date.now();
  let stored = safeReadJson(PROMISES_FILE, { promises: [] });
  if (!stored.promises) stored = { promises: [] };

  const staleMs = STALE_PROMISE_DAYS * 24 * 60 * 60 * 1000;

  // Prune stale entries before adding new ones
  stored.promises = stored.promises.filter(p => {
    const age = now - new Date(p.timestamp).getTime();
    return age <= staleMs;
  });

  const sessionId = (process.env.CLAUDE_SESSION_ID || 'unknown').slice(0, 64);
  for (const text of newPromises) {
    stored.promises.push({
      text,
      timestamp: new Date().toISOString(),
      sessionId,
    });
  }

  if (stored.promises.length > 50) {
    stored.promises = stored.promises.slice(-50);
  }

  try {
    atomicWrite(PROMISES_FILE, JSON.stringify(stored, null, 2));
  } catch { /* non-critical */ }
}

