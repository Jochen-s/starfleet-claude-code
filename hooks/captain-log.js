// Vault digest
// ---------------------------------------------------------------------------

/**
 * Write a session digest to the Obsidian vault.
 * Creates Claude-Sessions/ directory if needed.
 * Uses Obsidian-compatible frontmatter.
 *
 * @param {object} checkpoint
 * @param {object[]} actions
 * @param {object[]} tasks
 * @param {string[]} promises  Pre-extracted promise phrases
 */
function writeVaultDigest(checkpoint, actions, tasks, promises) {
  if (!VAULT_SESSIONS_DIR) return;
  try {
    const now = new Date();
    const dateStr = now.toISOString().slice(0, 10);
    const timeStr = now.toISOString().slice(11, 16).replace(':', '');
    const fileName = `${dateStr}-${timeStr}.md`;

    fs.mkdirSync(VAULT_SESSIONS_DIR, { recursive: true });

    const filePath = path.join(VAULT_SESSIONS_DIR, fileName);

    if (fs.existsSync(filePath)) return;

    const task = checkpoint.currentTask || 'General session';
    const hull = sanitizeForMd(checkpoint.hullIntegrity || 'Unknown');
    const modifiedFiles = extractModifiedFiles(actions);
    const completedActions = extractCompletedActions(actions);

    const completed = tasks.filter(t => (t.status || '').toLowerCase() === 'completed').length;
    const pending = tasks.filter(t => (t.status || '').toLowerCase() === 'pending').length;

    let md = '';

    md += `---\n`;
    md += `up: "[[Calendar]]"\n`;
    md += `created: ${dateStr}\n`;
    md += `tags:\n  - claude-session\n`;
    md += `hull: "${hull}"\n`;
    md += `files-changed: ${modifiedFiles.length}\n`;
    md += `tasks-completed: ${completed}\n`;
    md += `---\n\n`;

    md += `# Claude Session: ${dateStr}\n\n`;

    md += `## Goal\n\n${sanitizeForMd(task)}\n\n`;

    if (completedActions.length > 0) {
      md += `## Actions\n\n`;
      for (const a of completedActions.slice(-MAX_ACTIONS)) {
        md += `- ${a}\n`;
      }
      md += '\n';
    }

    if (modifiedFiles.length > 0) {
      md += `## Files Changed\n\n`;
      for (const f of modifiedFiles) {
        md += `- \`${sanitizeForMd(f).replace(/`/g, "'")}\`\n`;
      }
      md += '\n';
    }

    if (promises.length > 0) {
      md += `## Commitments\n\n`;
      for (const p of promises) {
        md += `- ${sanitizeForMd(p)}\n`;
      }
      md += '\n';
    }

    if (tasks.length > 0) {
      md += `## Tasks\n\n`;
      for (const t of tasks.slice(0, 10)) {
        const marker = (t.status || '').toLowerCase() === 'completed' ? 'x' : ' ';
        md += `- [${marker}] ${sanitizeForMd(t.subject || t.description || 'Unnamed')}\n`;
      }
      if (pending > 0) {
        md += `\n*${pending} tasks still pending*\n`;
      }
      md += '\n';
    }

    atomicWrite(filePath, md);

    // Prune old digests (>30 days)
    pruneOldDigests(VAULT_SESSIONS_DIR);
  } catch {
    // Non-critical; never block session end
  }
}

/**
 * Remove vault digest files older than VAULT_RETENTION_DAYS.
 * Parses YYYY-MM-DD from filename prefix. Scans at most 500 entries.
 *
 * @param {string} dir
 */
function pruneOldDigests(dir) {
  try {
    const entries = fs.readdirSync(dir).slice(0, 500);
    const cutoff = Date.now() - (VAULT_RETENTION_DAYS * 24 * 60 * 60 * 1000);
    for (const name of entries) {
      const dateMatch = name.match(/^(\d{4}-\d{2}-\d{2})/);
      if (dateMatch) {
        const fileDate = new Date(dateMatch[1]).getTime();
        if (fileDate < cutoff && !isNaN(fileDate)) {
          try { fs.unlinkSync(path.join(dir, name)); } catch { /* skip */ }
        }
      }
    }
  } catch { /* non-critical */ }
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  // Read and parse hook input from stdin (Stop event JSON)
  let hookData = {};
  try {
    const raw = fs.readFileSync(0, 'utf8');
    hookData = JSON.parse(raw);
  } catch {
    // Cannot parse stdin; proceed with empty hookData, still generate log
  }

  // Determine project root:
  //   1. hookData.cwd from Stop event (most current, set by Claude Code)
  //   2. process.cwd() fallback (reliable on all platforms)
  //   3. checkpoint.projectPath only if it passes safety check
  let projectRoot;
  try {
    const checkpoint = loadCheckpoint();

    // Resolve project root: prefer live sources over cached checkpoint
    projectRoot = (hookData && hookData.cwd)
      || process.cwd();

    // Use checkpoint.projectPath only if it is safe and plausible
    if (!projectRoot || projectRoot === '/') {
      const cp = checkpoint.projectPath;
      if (cp && typeof cp === 'string' && isSafeProjectRoot(cp)) {
        projectRoot = cp;
      }
    }

    const sessionId   = (hookData && hookData.session_id) || '';
    const lastMessage = (hookData && hookData.last_assistant_message) || '';
    const decisions   = Array.isArray(hookData && hookData.decisions) ? hookData.decisions : [];
    const actions    = loadRecentActions();
    const tasks      = loadTasks(sessionId);
    const promises   = extractPromises(actions);
    const startTasks = loadStartTasks();
    const delta      = startTasks.length > 0
      ? computeDelta(startTasks, tasks)
      : null;

    const md = renderHandoff(checkpoint, actions, tasks, promises, delta, lastMessage, decisions, projectRoot);

    // Track promises
    updatePromises(promises);

    // Write vault digest
    writeVaultDigest(checkpoint, actions, tasks, promises);

    const handoffTarget = resolveHandoffTarget(projectRoot);
    atomicWrite(handoffTarget, md);

  } catch {
    // Last-resort attempt: write a minimal handoff so the session
    // doesn't end silently with nothing to hand off to the next run.
    try {
      const fallbackRoot = (hookData && hookData.cwd) || process.cwd();
      const fallbackPath = resolveHandoffTarget(fallbackRoot);
      const fallbackMd   =
        `# Captain's Log, Supplemental\n\n` +
        `*Auto-generated: ${new Date().toISOString()}*\n` +
        `*Hull integrity: Unknown*\n\n` +
        `## Mission Status\n\n` +
        `**Current task**: Unknown, hook encountered an error reading cache files\n\n` +
        `## Recommended Next Steps\n\n` +
        `1. Run \`/resume\` to restore session context\n` +
        `2. Check task list with \`TaskList\` for pending work\n\n` +
        `---\n` +
        `*${AUTO_GENERATED_MARKER} (Stop event), degraded mode*\n`;
      atomicWrite(fallbackPath, fallbackMd);
    } catch {
      // Truly nothing we can do; exit 0 regardless
    }
  }

  process.exit(0);
}

main();
